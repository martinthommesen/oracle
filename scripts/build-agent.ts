// Renders plugins/oracle/agents/oracle.md, the oracle a plain agent file can
// define, from the prompts the hooks module registers.
//
//   node --experimental-strip-types scripts/build-agent.ts          write it
//   node --experimental-strip-types scripts/build-agent.ts --check  fail when stale

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

import { AGENT_NAME, FALLBACK_FEATURES, oracleDescription, oracleInstructions, oracleTools } from '../plugins/oracle/hooks/prompts.ts'

const target = fileURLToPath(new URL('../plugins/oracle/agents/oracle.md', import.meta.url))
const manifest = fileURLToPath(new URL('../plugins/oracle/.claude-plugin/plugin.json', import.meta.url))

// The fallback runs on the defaults the /config rows start from.
const { userConfig } = JSON.parse(readFileSync(manifest, 'utf8')) as { userConfig: Record<string, { default: string }> }

function indent(text: string): string {
  return text
    .split('\n')
    .map(line => (line === '' ? '' : `  ${line}`))
    .join('\n')
}

const rendered = [
  '---',
  '# Generated by scripts/build-agent.ts from plugins/oracle/hooks/prompts.ts: edit those, not this file.',
  '# The fallback oracle. With hooks modules on, the plugin registers the oracle on the model and effort',
  '# set in /config instead, with a read-only guard and read_thread.',
  `name: ${AGENT_NAME}`,
  'description: |',
  indent(oracleDescription(FALLBACK_FEATURES)),
  `model: ${userConfig.model!.default}`,
  `effort: ${userConfig.effort!.default}`,
  `tools: ${oracleTools(FALLBACK_FEATURES).join(', ')}`,
  'color: purple',
  '---',
  '',
  oracleInstructions(FALLBACK_FEATURES),
  '',
].join('\n')

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {
    // missing counts as stale
  }
  if (current !== rendered) {
    console.error('plugins/oracle/agents/oracle.md is out of date: run npm run build')
    process.exit(1)
  }
  console.log('agents/oracle.md is up to date')
} else {
  writeFileSync(target, rendered)
  console.log('wrote plugins/oracle/agents/oracle.md')
}
